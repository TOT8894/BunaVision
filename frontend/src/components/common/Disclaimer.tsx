import React from 'react'
import { AlertCircle, Info } from 'lucide-react'

export interface DisclaimerProps {
  variant?: 'banner' | 'card' | 'compact'
  className?: string
  showDetails?: boolean
}

export const Disclaimer: React.FC<DisclaimerProps> = ({
  variant = 'card',
  className = '',
  showDetails = false,
}) => {
  if (variant === 'compact') {
    return (
      <div
        role="note"
        aria-label="Preliminary AI assessment disclaimer"
        className={`flex items-center gap-2 text-xs text-amber-900 bg-amber-50 border border-amber-200/80 rounded-md px-3 py-1.5 ${className}`}
      >
        <Info className="h-4 w-4 shrink-0 text-amber-700" aria-hidden="true" />
        <span>
          <strong>Preliminary AI assessment only:</strong> Not an official coffee grade.
        </span>
      </div>
    )
  }

  if (variant === 'banner') {
    return (
      <aside
        role="note"
        aria-label="Important assessment disclaimer"
        className={`w-full bg-amber-50 border-y border-amber-200/80 px-4 py-3 text-amber-950 ${className}`}
      >
        <div className="mx-auto flex max-w-6xl items-start gap-3">
          <AlertCircle className="mt-0.5 h-5 w-5 shrink-0 text-amber-700" aria-hidden="true" />
          <div className="text-sm leading-relaxed">
            <p className="font-semibold text-amber-900">Preliminary Decision-Support Tool</p>
            <p className="text-amber-800">
              BunaVision provides preliminary AI predictions only. It is{' '}
              <strong className="font-semibold text-amber-950">
                not an official coffee grading system
              </strong>{' '}
              and must not be used as a final quality certification. All results require manual
              expert verification.
            </p>
          </div>
        </div>
      </aside>
    )
  }

  return (
    <div
      role="note"
      aria-label="Assessment limitations disclaimer"
      className={`rounded-lg border border-amber-200 bg-amber-50/70 p-4 text-amber-950 shadow-xs ${className}`}
    >
      <div className="flex items-start gap-3">
        <AlertCircle className="mt-0.5 h-5 w-5 shrink-0 text-amber-700" aria-hidden="true" />
        <div className="space-y-1 text-sm leading-relaxed">
          <p className="font-medium text-amber-900">Notice: Preliminary AI Screening</p>
          <p className="text-amber-800">
            Predictions are generated by a computer vision model and represent decision-support
            estimates. BunaVision does <strong className="font-medium text-amber-950">not</strong>{' '}
            provide official coffee grading.
          </p>
          {showDetails && (
            <ul className="mt-2 list-disc space-y-1 pl-4 text-xs text-amber-800/90">
              <li>Only supported visible defect classes are assessed.</li>
              <li>Hidden or internal defects cannot be reliably determined from a photograph.</li>
              <li>
                Confidence values reflect model prediction confidence, not guaranteed correctness.
              </li>
            </ul>
          )}
        </div>
      </div>
    </div>
  )
}
